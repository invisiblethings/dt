#!/usr/bin/env node
/**
 * Build step (zero dependencies). Wrangler runs this automatically before
 * `wrangler deploy` / `wrangler dev` (see [build] in wrangler.toml).
 *
 *  knowledge/system-prompt.md + knowledge/faq.md -> worker/src/knowledge.generated.js
 *  widget/chat.js                                 -> worker/src/widget.generated.js
 *  everything                                     -> worker/dist/worker.js (single file, for
 *                                                    pasting into the Cloudflare dashboard)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const src = join(here, '..', 'src');

const stripComments = (md) =>
  md
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

const prompt = stripComments(readFileSync(join(root, 'knowledge', 'system-prompt.md'), 'utf8'));
const faq = stripComments(readFileSync(join(root, 'knowledge', 'faq.md'), 'utf8'));
const widget = readFileSync(join(root, 'widget', 'chat.js'), 'utf8');
const etag = '"' + createHash('sha256').update(widget).digest('hex').slice(0, 16) + '"';

const header = '// AUTO-GENERATED by worker/scripts/build.mjs. Do not edit; edit the source file instead.\n';
const knowledgeJs =
  header + `export const SYSTEM_PROMPT_TEMPLATE = ${JSON.stringify(prompt)};\n` + `export const FAQ_TEXT = ${JSON.stringify(faq)};\n`;
const widgetJs = header + `export const WIDGET_ETAG = ${JSON.stringify(etag)};\n` + `export const WIDGET_JS = ${JSON.stringify(widget)};\n`;

writeFileSync(join(src, 'knowledge.generated.js'), knowledgeJs);
writeFileSync(join(src, 'widget.generated.js'), widgetJs);

// Single-file bundle for dashboard paste: inline the generated constants + lib.js, then the entry export.
const lib = readFileSync(join(src, 'lib.js'), 'utf8');
const strip = (s) => s.replace(header, '').replace(/^export (const|async function|function|class) /gm, '$1 ');
const importRe = /^import \{[^}]+\} from '\.\/(knowledge|widget)\.generated\.js';\n/gm;
const found = lib.match(importRe) || [];
if (found.length !== 2) throw new Error('build: expected exactly two generated imports in src/lib.js');
const bundle =
  header + strip(knowledgeJs) + strip(widgetJs) + strip(lib.replace(importRe, '')) + '\nexport default { fetch: handleFetch };\n';
mkdirSync(join(here, '..', 'dist'), { recursive: true });
writeFileSync(join(here, '..', 'dist', 'worker.js'), bundle);

console.log(`build: prompt ${prompt.length} chars, faq ${faq.length} chars, widget ${widget.length} bytes, etag ${etag}`);
